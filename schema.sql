-- Starter schema for UoG Public Health Academy.
-- Review and apply this SQL in your own Supabase SQL Editor.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  year_of_study integer check (year_of_study between 2 and 4),
  avatar_url text,
  is_approved boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid references public.profiles(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  sender_id uuid references public.profiles(id) on delete cascade,
  body text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.resources (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  file_url text not null,
  file_type text,
  uploaded_by uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.messages enable row level security;
alter table public.resources enable row level security;

-- Initial policies are intentionally conservative. Add role-specific policies
-- before enabling registration, uploads, chat, or admin actions in production.
create policy "Profiles visible to authenticated users" on public.profiles
  for select to authenticated using (true);
create policy "Users can insert own profile" on public.profiles
  for insert to authenticated with check (auth.uid() = id);
create policy "Users can update own profile" on public.profiles
  for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);

create policy "Approved users can read posts" on public.posts
  for select to authenticated using (
    exists (select 1 from public.profiles p where p.id = auth.uid() and p.is_approved = true)
  );
create policy "Approved users can create posts" on public.posts
  for insert to authenticated with check (
    auth.uid() = user_id and exists (
      select 1 from public.profiles p where p.id = auth.uid() and p.is_approved = true
    )
  );

create policy "Authenticated users can read resources" on public.resources
  for select to authenticated using (true);
